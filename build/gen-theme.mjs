import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const themeDefaults = process.argv[2];
if (!themeDefaults) {
  console.error("usage: node build/gen-theme.mjs <.../extensions/theme-defaults>");
  process.exit(2);
}

const stripJsonc = (s) =>
  JSON.parse(s.replace(/^\s*\/\/.*$/gm, "").replace(/,(\s*[}\]])/g, "$1"));
const load = (f) => stripJsonc(fs.readFileSync(path.join(themeDefaults, "themes", f), "utf8"));

function resolve(file) {
  const t = load(file);
  let base = { colors: {}, tokenColors: [], semanticTokenColors: {} };
  if (t.include) base = resolve(t.include.replace("./", ""));
  return {
    colors: { ...base.colors, ...(t.colors || {}) },
    tokenColors: [...base.tokenColors, ...(t.tokenColors || [])],
    semanticTokenColors: { ...base.semanticTokenColors, ...(t.semanticTokenColors || {}) },
    semanticHighlighting: t.semanticHighlighting ?? base.semanticHighlighting ?? true,
  };
}

